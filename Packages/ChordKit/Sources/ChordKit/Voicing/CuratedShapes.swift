        "guitar/standard": guitarStandard,
        "ukulele/highG": ukuleleGCEA,
    ]

    static func shapes(instrumentID: String, tuningID: String, chord: Chord) -> [String] {
        tables["\(instrumentID)/\(tuningID)"]?[chord.type.id]?[chord.rootName] ?? []
    }

