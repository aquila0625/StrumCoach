///
/// 写法：品位按定弦的物理顺序连写，`x` 不弹，`0` 空弦，10 品以上用 a=10 b=11 c=12。
/// 手指编号不在这里写，统一由 `FingerAssigner` 算，这样两边不会不一致。
/// 每条都会过一遍和生成按法相同的验证；不合格的会被丢弃，单元测试里有一条专门保证没有被丢弃的。
